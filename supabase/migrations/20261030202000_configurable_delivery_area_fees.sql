-- ============================================================
-- HENA - Configurable delivery area fees
--
-- The area surcharge used to be a hard coded CASE expression
-- inside calculate_delivery_area_surcharge(). It is now driven by
-- the delivery_areas catalog, so the administrator can add, edit,
-- activate and deactivate areas and set a fee for each of them.
--
-- The delivery fee breakdown is persisted on the order so that a
-- historical order always shows the fees that were actually
-- charged, even after the configuration changes:
--
--   orders.delivery_base_fee   : the standard delivery fee
--   orders.multi_store_fee     : the extra charge for extra stores
--   orders.delivery_area_fee   : the fee of the selected area
--   orders.delivery_fee        : the sum of the three above
--                                  (unchanged meaning, still the
--                                   amount the customer pays)
--
-- The existing fee rules are preserved:
--   * base fee                 : delivery_settings.base_fee
--   * multi store charge       : one extra_store_fee per store
--                                 beyond delivery_settings
--                                 .included_stores (never per
--                                 product)
--   * area fee                 : the fee of the selected area
-- ============================================================

-- ------------------------------------------------------------
-- 1) Make sure the catalog exists and can carry a fee.
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.delivery_areas (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);

ALTER TABLE public.delivery_areas
  ADD COLUMN IF NOT EXISTS delivery_fee numeric(12,2) NOT NULL DEFAULT 0;

ALTER TABLE public.delivery_areas
  ADD COLUMN IF NOT EXISTS updated_at timestamp with time zone
  NOT NULL DEFAULT now();

ALTER TABLE public.delivery_areas
  DROP CONSTRAINT IF EXISTS delivery_areas_delivery_fee_check;

ALTER TABLE public.delivery_areas
  ADD CONSTRAINT delivery_areas_delivery_fee_check
  CHECK (delivery_fee >= 0);

ALTER TABLE public.delivery_areas
  DROP CONSTRAINT IF EXISTS delivery_areas_name_key;

ALTER TABLE public.delivery_areas
  ADD CONSTRAINT delivery_areas_name_key UNIQUE (name);

-- Preserve the behaviour that was hard coded before: the areas that
-- used to be free stay free, every other area keeps the old 5 EGP.
UPDATE public.delivery_areas
SET delivery_fee = CASE
  WHEN btrim(name) IN ('الأندلس', '247') THEN 0
  ELSE 5
END
WHERE delivery_fee IS NULL
   OR delivery_fee = 0;

