CREATE OR REPLACE FUNCTION public.admin_update_default_area_fee(
  p_fee numeric(12,2)
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_fee numeric(12,2);
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only admins can update delivery settings';
  END IF;

  IF p_fee IS NULL OR p_fee < 0 THEN
    RAISE EXCEPTION 'Default area fee must be zero or greater';
  END IF;

  UPDATE public.delivery_settings
  SET default_area_fee = p_fee,
      updated_at = now()
  WHERE id = 1
  RETURNING default_area_fee INTO v_fee;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Delivery settings are not configured';
  END IF;

  RETURN jsonb_build_object('default_area_fee', v_fee);
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_update_default_area_fee(numeric)
FROM PUBLIC;

