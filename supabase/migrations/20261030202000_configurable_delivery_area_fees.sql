-- ------------------------------------------------------------
-- 4) The authoritative fee calculation.
--
--    base fee        : the standard delivery fee
--    multi store fee : one extra_store_fee per store beyond
--                      included_stores (applied once, never per
--                      product)
--    area fee        : the fee of the selected delivery area
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.calculate_delivery_fees(
  p_store_count integer,
  p_area text
)
RETURNS TABLE (
  base_fee numeric(12,2),
  multi_store_fee numeric(12,2),
  area_fee numeric(12,2),
  total_fee numeric(12,2)
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_store_count integer := COALESCE(p_store_count, 0);
  v_base_fee numeric(12,2) := 0;
  v_included_stores integer := 1;
  v_extra_store_fee numeric(12,2) := 0;
  v_default_area_fee numeric(12,2) := 0;
  v_multi_store_fee numeric(12,2) := 0;
  v_area_fee numeric(12,2);
BEGIN
  SELECT
    COALESCE(ds.base_fee, 0),
    COALESCE(ds.included_stores, 1),
    COALESCE(ds.extra_store_fee, 0),
    COALESCE(ds.default_area_fee, 0)
  INTO v_base_fee, v_included_stores, v_extra_store_fee, v_default_area_fee
  FROM public.delivery_settings ds
  WHERE ds.id = 1;

  IF v_store_count <= 0 THEN
    v_base_fee := 0;
  END IF;

  IF v_store_count > v_included_stores THEN
    v_multi_store_fee :=
      (v_store_count - v_included_stores) * v_extra_store_fee;
  END IF;

  SELECT da.delivery_fee
  INTO v_area_fee
  FROM public.delivery_areas da
  WHERE lower(btrim(da.name)) = lower(btrim(COALESCE(p_area, '')))
    AND da.is_active
  LIMIT 1;

  IF v_area_fee IS NULL THEN
    v_area_fee := v_default_area_fee;
  END IF;

  base_fee := v_base_fee;
  multi_store_fee := v_multi_store_fee;
  area_fee := v_area_fee;
  total_fee := v_base_fee + v_multi_store_fee + v_area_fee;

  RETURN NEXT;
END;
$function$;

REVOKE ALL ON FUNCTION public.calculate_delivery_fees(integer, text)
FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.calculate_delivery_fees(integer, text)
TO authenticated;

-- ------------------------------------------------------------
-- 5) The legacy surcharge helper now reads the catalog, so any
--    caller that still uses it behaves consistently.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.calculate_delivery_area_surcharge(
  p_area text
)
RETURNS numeric(12,2)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_fee numeric(12,2);
  v_default_area_fee numeric(12,2) := 0;
BEGIN
  SELECT COALESCE(ds.default_area_fee, 0)
  INTO v_default_area_fee
  FROM public.delivery_settings ds
  WHERE ds.id = 1;

  SELECT da.delivery_fee
  INTO v_fee
  FROM public.delivery_areas da
  WHERE lower(btrim(da.name)) = lower(btrim(COALESCE(p_area, '')))
    AND da.is_active
  LIMIT 1;

  IF v_fee IS NULL THEN
    v_fee := v_default_area_fee;
  END IF;

  RETURN v_fee;
END;
$function$;

REVOKE ALL ON FUNCTION public.calculate_delivery_area_surcharge(text)
FROM PUBLIC;

-- ------------------------------------------------------------
-- 6) Patch the authoritative order functions.
--
--    The functions are patched in place so every existing guard and
--    business rule is preserved. Each anchor is verified and the
--    migration fails loudly when something does not match.
-- ------------------------------------------------------------

DO $block$
DECLARE
  v_function_oid oid;
  v_signature text;
  v_definition text;
  v_before text;
  v_area_expression text;
  v_found integer := 0;
BEGIN
  FOR v_function_oid IN
    SELECT p.oid
    FROM pg_proc p
    JOIN pg_namespace n
      ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
      AND p.oid::regprocedure::text IN (
        'create_unified_order(uuid,jsonb,payment_method,text)',
        'edit_unified_order(uuid,jsonb)'
      )
    ORDER BY p.oid::regprocedure::text
  LOOP
    v_found := v_found + 1;
    v_signature := v_function_oid::regprocedure::text;
    v_definition := pg_get_functiondef(v_function_oid);
    v_before := v_definition;

    IF position('calculate_delivery_fees' IN v_definition) <> 0 THEN
      RAISE EXCEPTION
        '% already contains the delivery fee breakdown',
        v_signature;
    END IF;

    -- create_unified_order reads the address that is being used,
    -- edit_unified_order reads the area of the stored order.
    IF v_signature =
         'create_unified_order(uuid,jsonb,payment_method,text)'
    THEN
      v_area_expression := 'v_address.area';
    ELSE
      v_area_expression := 'v_order.delivery_area';
    END IF;

    -- 6a) Declare the breakdown variables.
    IF position('v_delivery_fee numeric(12,2) := 0;' IN v_definition) = 0 THEN
      RAISE EXCEPTION
        'Delivery fee declaration was not found in %',
        v_signature;
    END IF;

    v_definition := replace(
      v_definition,
      'v_delivery_fee numeric(12,2) := 0;',
      E'v_delivery_fee numeric(12,2) := 0;\n' ||
      E'  v_delivery_base_fee numeric(12,2) := 0;\n' ||
      E'  v_multi_store_fee numeric(12,2) := 0;\n' ||
      E'  v_delivery_area_fee numeric(12,2) := 0;'
    );

    -- 6b) Replace the fee calculation with the authoritative one.
    IF position(
      'SELECT public.calculate_delivery_fee(v_store_count)'
      IN v_definition
    ) = 0 THEN
      RAISE EXCEPTION
        'Delivery fee calculation was not found in %',
        v_signature;
    END IF;

    v_definition := replace(
      v_definition,
      E'SELECT public.calculate_delivery_fee(v_store_count)\n' ||
      E'  INTO v_delivery_fee;',
      E'SELECT public.calculate_delivery_fees(\n' ||
      E'    v_store_count,\n' ||
      E'    ' || v_area_expression || E'\n' ||
      E'  )\n' ||
      E'  INTO v_delivery_fee,\n' ||
      E'    v_delivery_base_fee,\n' ||
      E'    v_multi_store_fee,\n' ||
      E'    v_delivery_area_fee;'
    );

    -- 6c) The old hard coded surcharge is now part of the breakdown.
    --      The statement was inserted by an earlier migration with
    --      exactly this shape, so it is removed verbatim.
    IF position(
      'public.calculate_delivery_area_surcharge(' ||
      v_area_expression || ');'
      IN v_definition
    ) <> 0 THEN
      v_definition := replace(
        v_definition,
        E'  v_delivery_fee :=\n' ||
        E'    v_delivery_fee +\n' ||
        E'    public.calculate_delivery_area_surcharge(' ||
        v_area_expression || E');',
        ''
      );
    END IF;

    IF v_definition = v_before THEN
      RAISE EXCEPTION
        'Nothing could be patched in %',
        v_signature;
    END IF;

    EXECUTE v_definition;
  END LOOP;

  IF v_found <> 2 THEN
    RAISE EXCEPTION
      'Expected 2 authoritative order functions, found %',
      v_found;
  END IF;
END;
$block$;

-- ------------------------------------------------------------
-- 7) Store the breakdown with the order.
-- ------------------------------------------------------------

DO $block$
DECLARE
  v_definition text;

  -- create_unified_order
  v_create_columns text;
  v_create_values text;
BEGIN
  SELECT pg_get_functiondef(
    'public.create_unified_order(uuid,jsonb,payment_method,text)'::regprocedure
  )
  INTO v_definition;

  v_create_columns := E'    delivery_fee,\n    extra_fee,';
  v_create_values := E'    v_subtotal,\n    v_delivery_fee,\n    0,';

  IF position(v_create_columns IN v_definition) = 0 THEN
    RAISE EXCEPTION
      'Order column list was not found in create_unified_order';
  END IF;

  IF position(v_create_values IN v_definition) = 0 THEN
    RAISE EXCEPTION
      'Order value list was not found in create_unified_order';
  END IF;

  v_definition := replace(
    v_definition,
    v_create_columns,
    E'    delivery_fee,\n' ||
    E'    delivery_base_fee,\n' ||
    E'    multi_store_fee,\n' ||
    E'    delivery_area_fee,\n' ||
    E'    extra_fee,'
  );

  v_definition := replace(
    v_definition,
    v_create_values,
    E'    v_subtotal,\n' ||
    E'    v_delivery_fee,\n' ||
    E'    v_delivery_base_fee,\n' ||
    E'    v_multi_store_fee,\n' ||
    E'    v_delivery_area_fee,\n' ||
    E'    0,'
  );

  EXECUTE v_definition;
END;
$block$;

DO $block$
DECLARE
  v_definition text;
  v_anchor text;
BEGIN
  SELECT pg_get_functiondef(
    'public.edit_unified_order(uuid,jsonb)'::regprocedure
  )
  INTO v_definition;

  v_anchor := E'    subtotal = v_subtotal,\n    delivery_fee = v_delivery_fee';

  IF position(v_anchor IN v_definition) = 0 THEN
    RAISE EXCEPTION
      'Order update block was not found in edit_unified_order';
  END IF;

  v_definition := replace(
    v_definition,
    v_anchor,
    E'    subtotal = v_subtotal,\n' ||
    E'    delivery_fee = v_delivery_fee,\n' ||
    E'    delivery_base_fee = v_delivery_base_fee,\n' ||
    E'    multi_store_fee = v_multi_store_fee,\n' ||
    E'    delivery_area_fee = v_delivery_area_fee'
  );

  EXECUTE v_definition;
END;
$block$;

-- ------------------------------------------------------------
-- 8) Read the catalog.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.get_delivery_areas(
  p_include_inactive boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  RETURN COALESCE(
    (
      SELECT jsonb_agg(
        jsonb_build_object(
          'id', da.id,
          'name', da.name,
          'delivery_fee', da.delivery_fee,
          'sort_order', da.sort_order,
          'is_active', da.is_active
        )
        ORDER BY da.sort_order, da.id
      )
      FROM public.delivery_areas da
      WHERE p_include_inactive OR da.is_active
    ),
    '[]'::jsonb
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.get_delivery_areas(boolean) FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.get_delivery_areas(boolean)
TO authenticated;

GRANT EXECUTE ON FUNCTION public.get_delivery_areas(boolean)
TO anon;

-- ------------------------------------------------------------
-- 9) Admin management of the catalog.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.admin_upsert_delivery_area(
  p_id integer,
  p_name text,
  p_delivery_fee numeric(12,2),
  p_sort_order integer DEFAULT 0,
  p_is_active boolean DEFAULT true
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_id integer;
  v_name text;
  v_fee numeric(12,2);
  v_sort_order integer;
  v_is_active boolean;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only admins can manage delivery areas';
  END IF;

  IF p_name IS NULL OR btrim(p_name) = '' THEN
    RAISE EXCEPTION 'Delivery area name is required';
  END IF;

  IF p_delivery_fee IS NULL OR p_delivery_fee < 0 THEN
    RAISE EXCEPTION 'Delivery fee must be zero or greater';
  END IF;

  v_name := btrim(p_name);
  v_fee := p_delivery_fee;
  v_sort_order := COALESCE(p_sort_order, 0);
  v_is_active := COALESCE(p_is_active, true);

  IF p_id IS NULL THEN
    INSERT INTO public.delivery_areas (
      name,
      delivery_fee,
      sort_order,
      is_active
    )
    VALUES (
      v_name,
      v_fee,
      v_sort_order,
      v_is_active
    )
    ON CONFLICT (name) DO UPDATE
    SET delivery_fee = EXCLUDED.delivery_fee,
        sort_order = EXCLUDED.sort_order,
        is_active = EXCLUDED.is_active,
        updated_at = now()
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.delivery_areas
    SET name = v_name,
        delivery_fee = v_fee,
        sort_order = v_sort_order,
        is_active = v_is_active,
        updated_at = now()
    WHERE id = p_id
    RETURNING id INTO v_id;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Delivery area not found';
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'id', v_id,
    'name', v_name,
    'delivery_fee', v_fee,
    'sort_order', v_sort_order,
    'is_active', v_is_active
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_upsert_delivery_area(
  integer,
  text,
  numeric,
  integer,
  boolean
)
FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.admin_upsert_delivery_area(
