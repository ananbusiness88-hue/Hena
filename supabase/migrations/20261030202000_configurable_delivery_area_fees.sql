-- ------------------------------------------------------------
-- 11) Verification.
-- ------------------------------------------------------------

DO $verify$
DECLARE
  v_definition text;
BEGIN
  SELECT pg_get_functiondef(
    'public.create_unified_order(uuid,jsonb,payment_method,text)'::regprocedure
  )
  INTO v_definition;

  IF position('calculate_delivery_fees' IN v_definition) = 0 THEN
    RAISE EXCEPTION
      'create_unified_order does not use calculate_delivery_fees';
  END IF;

  IF position('delivery_area_fee' IN v_definition) = 0 THEN
    RAISE EXCEPTION
      'create_unified_order does not store the delivery fee breakdown';
  END IF;

  SELECT pg_get_functiondef(
    'public.edit_unified_order(uuid,jsonb)'::regprocedure
  )
  INTO v_definition;

  IF position('calculate_delivery_fees' IN v_definition) = 0 THEN
    RAISE EXCEPTION
      'edit_unified_order does not use calculate_delivery_fees';
  END IF;

  IF position('delivery_area_fee' IN v_definition) = 0 THEN
    RAISE EXCEPTION
      'edit_unified_order does not store the delivery fee breakdown';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'orders'
      AND column_name = 'multi_store_fee'
  ) THEN
    RAISE EXCEPTION 'orders.multi_store_fee is missing';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'delivery_areas'
      AND column_name = 'delivery_fee'
  ) THEN
    RAISE EXCEPTION 'delivery_areas.delivery_fee is missing';
  END IF;
END;
$verify$;
