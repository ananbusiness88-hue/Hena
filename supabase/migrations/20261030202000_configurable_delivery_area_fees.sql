  text,
  numeric,
  integer,
  boolean
)
TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_set_delivery_area_active(
  p_id integer,
  p_is_active boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_area public.delivery_areas%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only admins can manage delivery areas';
  END IF;

  UPDATE public.delivery_areas
  SET is_active = COALESCE(p_is_active, false),
      updated_at = now()
  WHERE id = p_id
  RETURNING * INTO v_area;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Delivery area not found';
  END IF;

  RETURN jsonb_build_object(
    'id', v_area.id,
    'name', v_area.name,
    'delivery_fee', v_area.delivery_fee,
    'sort_order', v_area.sort_order,
    'is_active', v_area.is_active
  );
END;
$function$;

